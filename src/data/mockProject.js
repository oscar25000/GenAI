// Compute team load from tasks for first render.
export function computeTeamLoad(project) {
  const totals = Object.fromEntries(project.team.map((m) => [m.id, 0]))
  for (const t of project.tasks) {
    if (t.assignee && totals[t.assignee] !== undefined) {
      totals[t.assignee] += t.hours
    }
  }
  const grand = Math.max(1, Object.values(totals).reduce((a, b) => a + b, 0))
  return project.team.map((m) => ({
    ...m,
    hours: totals[m.id],
    load: Math.round((totals[m.id] / grand) * 100),
  }))
}
